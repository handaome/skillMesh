-- 审计表按月分区（设计文档 §10 审计；docs/遗留与已知取舍.md「审计数据」那条）。
--
-- 为什么分区：审计只写不改，留着的是历史流水。到期要清时，
-- 普通表只能 DELETE 一行行删（还带着索引与 bloat），
-- 分区表直接 DROP 分区——一条语句的事，删完空间也还回去。
--
-- 步骤：建新表 → 建月度分区 → 搬老数据 → 删老表 → 对齐序列 → 建索引。
-- 先建分区再搬数据：搬过去的行按 occurred_at 路由，正好落到对应月份，
-- 不用事后倒腾。
--
-- 老表是 bigserial 主键 (id)，分区表的主键必须带分区键，
-- 所以主键改成 (id, occurred_at)：同一个 id 可以出现在不同月份里，
-- 但 identity 序列保证 id 本身不重复。

ALTER TABLE audit_events RENAME TO audit_events_legacy;

CREATE TABLE audit_events (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at     timestamptz NOT NULL DEFAULT now(),
    actor_user_id   uuid REFERENCES users(id) ON DELETE SET NULL,
    organization_id uuid REFERENCES organizations(id) ON DELETE SET NULL,
    device_id       uuid REFERENCES devices(id) ON DELETE SET NULL,
    action          text NOT NULL,
    target_type     text NOT NULL,
    target_id       text,
    outcome         text NOT NULL CHECK (outcome IN ('success', 'denied', 'failure')),
    request_id      text,
    -- 存文本而不是 inet：审计只记录、不拿它做运算，
    -- 而 inet 在 JDBC 侧没有对应类型，得多带一个驱动依赖。
    ip_address      varchar(64),
    user_agent      text,
    details_json    jsonb NOT NULL DEFAULT '{}'::jsonb
                    CHECK (jsonb_typeof(details_json) = 'object'),
    PRIMARY KEY (id, occurred_at)
) PARTITION BY RANGE (occurred_at);

-- 月度分区：两年前到下个月。
-- 更早的老数据落默认分区，更新的分区由定时任务按需补。
DO $$
DECLARE
    month_start date;
BEGIN
    FOR month_start IN
        SELECT generate_series(date_trunc('month', now()) - interval '24 months',
                               date_trunc('month', now()) + interval '1 month',
                               interval '1 month')::date
    LOOP
        EXECUTE format(
            'CREATE TABLE audit_events_%s PARTITION OF audit_events FOR VALUES FROM (%L) TO (%L)',
            to_char(month_start, 'YYYY_MM'),
            month_start,
            (month_start + interval '1 month')::date);
    END LOOP;
END $$;

-- 默认分区兜底：没覆盖到的月份（更早的老数据、时钟跑偏的将来）先落这儿，
-- 定时任务会把它们归位。
CREATE TABLE audit_events_default PARTITION OF audit_events DEFAULT;

INSERT INTO audit_events (id, occurred_at, actor_user_id, organization_id, device_id, action,
                          target_type, target_id, outcome, request_id, ip_address, user_agent,
                          details_json)
SELECT id, occurred_at, actor_user_id, organization_id, device_id, action,
       target_type, target_id, outcome, request_id, ip_address, user_agent, details_json
FROM audit_events_legacy;

DROP TABLE audit_events_legacy;

-- 序列接着老数据往下发：identity 序列从 1 起，不对齐就跟老行撞 id。
SELECT setval(pg_get_serial_sequence('audit_events', 'id'),
              GREATEST(COALESCE((SELECT max(id) FROM audit_events), 0), 1));

CREATE INDEX idx_audit_events_time ON audit_events (occurred_at DESC);
CREATE INDEX idx_audit_events_target ON audit_events (target_type, target_id, occurred_at DESC);
