-- skill_call_records：Skill 的实际调用流水。
--
-- 回答的是「哪个 Skill 真的被用起来、用了多少次」。
-- 与 installations（装在哪台机器的哪个目录）、audit_events（谁动了什么）
-- 都不是一回事：前两个记的是分发与治理，这张表记的是真实使用。
--
-- 量级：单机每天几十次，团队一年万级以内，暂时不分区。
-- 真到了分区那一步，照 audit_events 的月度分区模式改（主键要带上分区键）。

CREATE TABLE skill_call_records (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 客户端生成的幂等键：网络抖动重发不会把一次调用算成两次。
    event_id        varchar(64) NOT NULL,
    occurred_at     timestamptz NOT NULL DEFAULT now(),
    -- 上报者。人被删了记录留着——历史事实不该随人消失，署名置空即可。
    actor_user_id   uuid REFERENCES users(id) ON DELETE SET NULL,
    -- 匹配上的云端 Skill。本地装的 Skill 不一定在云端，匹配不到就留空，
    -- 只按 skill_name 统计。
    skill_id        uuid REFERENCES skills(id) ON DELETE SET NULL,
    organization_id uuid REFERENCES organizations(id) ON DELETE SET NULL,
    skill_name      varchar(128) NOT NULL,
    -- Agent 名不设枚举约束：企业内网自建的 Agent 不在服务端的枚举里，
    -- 限死取值的话这类调用就报不上来了。
    agent           text NOT NULL DEFAULT 'claude-code',
    project_path    varchar(512),
    -- 调用参数只留开头一段：参数里可能夹着文件内容，不适合整段落库。
    args_preview    varchar(1000),
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_skill_call_records_event UNIQUE (event_id)
);

CREATE INDEX idx_skill_call_records_skill ON skill_call_records (skill_name, occurred_at DESC);
CREATE INDEX idx_skill_call_records_actor ON skill_call_records (actor_user_id, occurred_at DESC);
CREATE INDEX idx_skill_call_records_org ON skill_call_records (organization_id, occurred_at DESC);

COMMENT ON TABLE skill_call_records IS 'Skill 实际调用流水：谁在什么时候调用了哪个 Skill';
COMMENT ON COLUMN skill_call_records.event_id IS '客户端幂等键，重复上报按它去重';
COMMENT ON COLUMN skill_call_records.args_preview IS '调用参数开头一段，仅供定位，不做全文检索';
